// Regenerates src/workspace/workspace-fonts.css and copies the woff2 files into src/workspace/fonts/ from the
// @fontsource-variable packages (run: npm i --no-save @fontsource-variable/inter@5.3.0 @fontsource-variable/newsreader@5.3.0 && node scripts/gen-fonts.mjs).
// The files live inside this package so the CSS works wherever the package is installed.
// Why: every font is served from our own origin, so a visitor's browser never contacts Google Fonts.
// The packages name their families "Inter Variable" etc.; the app's CSS says 'Inter', so the generated
// @font-face blocks keep the original family names. Only the latin and latin-ext subsets are kept
// (the app is English; the browser fetches a subset file only when a character in its range is drawn).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkgDir = (p) => path.join(root, "node_modules", "@fontsource-variable", p);
const KEEP = /^\/\* [a-z0-9-]+-(latin|latin-ext)-/;

const OUT = {
  "workspace-fonts.css": [
    { family: "Inter", pkg: "inter", files: ["wght.css"] },
    { family: "Newsreader", pkg: "newsreader", files: ["opsz.css", "opsz-italic.css"] },
  ],
};

function convert({ family, pkg, files }) {
  const out = [];
  for (const f of files) {
    const css = fs.readFileSync(path.join(pkgDir(pkg), f), "utf8");
    for (const block of css.split(/\n\n/)) {
      if (!KEEP.test(block.trim())) continue;
      out.push(
        block.trim()
          .replace(`font-family: '${family} Variable'`, `font-family: '${family}'`)
          .replace(/url\(\.\/files\//, `url(./fonts/`),
      );
    }
  }
  for (const b of out) {
    const m = b.match(/url\(\.\/fonts\/([^)]+)\)/);
    fs.copyFileSync(path.join(pkgDir(pkg), "files", m[1]), path.join(root, "src", "workspace", "fonts", m[1]));
  }
  fs.copyFileSync(path.join(pkgDir(pkg), "LICENSE"), path.join(root, "src", "workspace", "fonts", `LICENSE-${pkg}-OFL.txt`));
  return out;
}

fs.mkdirSync(path.join(root, "src", "workspace", "fonts"), { recursive: true });
for (const [name, spec] of Object.entries(OUT)) {
  const blocks = (Array.isArray(spec) ? spec : [spec]).flatMap(convert);
  const head = "/* Generated by scripts/gen-fonts.mjs from @fontsource-variable/* (SIL OFL 1.1; see src/workspace/fonts/LICENSE-*). Do not edit by hand. */\n";
  fs.writeFileSync(path.join(root, "src", "workspace", name), head + blocks.join("\n\n") + "\n");
}
